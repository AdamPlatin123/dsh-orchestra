// Pins the Claude host (alpha 0.2 design §1 "防篡改"; orchestra app step 4): writes the sha256 of
// hosts/claude/host.mjs, hosts/claude/host-core.mjs and the installed SDK's sdk.mjs into
// src/owned/claude-pins.ts. orchestrad checks the three files against these pins when it starts (a
// mismatch keeps owned Claude sessions off) and the spawn gate checks them again before every host it
// starts (host-tampered). test/owned/claude-pins.test.ts fails when the host files and the pins part ways.
//   node scripts/pin-claude-host.ts      (rewrites src/owned/claude-pins.ts; run it after editing the host)
//
// Without hosts/claude/node_modules the SDK's pin is kept as it is: the SDK is not in the repository
// (its licence is proprietary, alpha 0.2 design §1), so only a machine that installed it can pin it.
// Listed in EXEMPT_SCRIPTS (test/helpers/scan-rules.ts): it reads three files of the repository and
// writes the one generated file, and touches no harness root.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../', import.meta.url));
export const OUT = path.join(REPO, 'src', 'owned', 'claude-pins.ts');
export const SDK_VERSION = '0.3.287';
export const PINNED: readonly string[] = Object.freeze([
  'hosts/claude/host.mjs',
  'hosts/claude/host-core.mjs',
  'hosts/claude/node_modules/@anthropic-ai/claude-agent-sdk/sdk.mjs',
]);

export const sha256 = (bytes: Buffer): string => createHash('sha256').update(bytes).digest('hex');

/** The pin of each file: its hash now, or (for a file not on disk) the pin `kept` had. */
export function pinsNow(repo: string = REPO, kept: Readonly<Record<string, string>> = {}): Record<string, string> {
  const out: Record<string, string> = {};
  for (const rel of PINNED) {
    const abs = path.join(repo, ...rel.split('/'));
    if (fs.existsSync(abs)) out[rel] = sha256(fs.readFileSync(abs));
    else if (kept[rel] !== undefined) out[rel] = kept[rel]!;
    else throw new Error(`pin-claude-host: ${rel} is missing and has no pin to keep`);
  }
  return out;
}

export function render(pins: Readonly<Record<string, string>>): string {
  const rows = PINNED.map((rel) => `  '${rel}': '${pins[rel]}',`);
  return `// Generated by scripts/pin-claude-host.ts; do not edit, run the script again after changing the host.
// The sha256 of the Claude host's files and of the SDK entry it loads (alpha 0.2 design §1). orchestrad
// checks them at startup and the spawn gate before every host start (src/owned/claude-site.ts).
import { frozen } from '../../shared/frozen.js';

/** The Agent SDK version the host was pinned with (hosts/claude/package.json). */
export const CLAUDE_SDK_VERSION = '${SDK_VERSION}';

/** Repository-relative path (forward slashes) -> sha256 of its bytes. */
export const CLAUDE_HOST_PINS: Readonly<Record<string, string>> = frozen({
${rows.join('\n')}
});
`;
}

if (import.meta.main) {
  let kept: Record<string, string> = {};
  if (fs.existsSync(OUT)) {
    for (const m of fs.readFileSync(OUT, 'utf8').matchAll(/^ {2}'([^']+)': '([0-9a-f]{64})',$/gm)) kept[m[1]!] = m[2]!;
  }
  const pins = pinsNow(REPO, kept);
  fs.writeFileSync(OUT, render(pins));
  console.log(`pin-claude-host: ${PINNED.length} pins into ${path.relative(REPO, OUT)}`);
}
