// Pins procguard's source (orchestra app: owned sessions in procguard Jobs): writes the sha256 of
// native/procguard/ProcGuard.cs into src/os/procguard-pins.ts. orchestrad builds procguard only from a
// source that matches this pin (src/os/procguard.ts ensureProcguard), into a site dir named by it; a
// source that does not match is never compiled, and the owned sessions run without Jobs (no brake),
// with the reason on the page. test/os/procguard-pins.test.ts fails when the source and the pin part ways.
//   node scripts/pin-procguard.ts      (rewrites src/os/procguard-pins.ts; run it after a reviewed change)
//
// Listed in EXEMPT_SCRIPTS (test/helpers/scan-rules.ts): it reads one file of the repository and writes
// the one generated file, and touches no harness root.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../', import.meta.url));
export const OUT = path.join(REPO, 'src', 'os', 'procguard-pins.ts');
export const SOURCE = path.join(REPO, 'native', 'procguard', 'ProcGuard.cs');

export const sha256 = (bytes: Buffer): string => createHash('sha256').update(bytes).digest('hex');

export function render(hash: string): string {
  return `// Generated by scripts/pin-procguard.ts; do not edit, run the script again after changing the source.
// The sha256 of native/procguard/ProcGuard.cs: orchestrad compiles procguard only from a source with this
// hash, into ORCHESTRA_HOME\\runtime\\procguard\\<this hash>\\ (src/os/procguard.ts ensureProcguard).

/** sha256 of native/procguard/ProcGuard.cs, lowercase hex. */
export const PROCGUARD_SOURCE_SHA256 = '${hash}';
`;
}

if (import.meta.main) {
  fs.writeFileSync(OUT, render(sha256(fs.readFileSync(SOURCE))));
  console.log(`pin-procguard: wrote ${path.relative(REPO, OUT)}`);
}
