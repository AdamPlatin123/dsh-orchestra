// Embeds the tower page's static files into src/server/ui-assets.ts (0.1 alpha design §4 "Codegen", kept
// for the tower, orchestra app plan §5):
// no src module can read a file from disk but through the read gate, and the gate has no root for the
// repo's own ui/ and shared/ (adding one would change its policy), so the peek server serves them
// from this generated module instead. test/server/ui-assets-drift.test.ts fails when the module and
// the files on disk part ways.
//   node scripts/embed-ui.ts            (rewrites src/server/ui-assets.ts)
//
// Each body is stored as hex: the static scan reads src/ as daemon code, and the page's own code
// rightly holds words daemon code may not (its clock, its one fetch to /api/). Hex has no letter past
// f, so no banned word can appear in it. Listed in EXEMPT_SCRIPTS (test/helpers/scan-rules.ts): it
// reads the repo's ui/ and shared/ and writes the one generated file, and touches no harness root.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../', import.meta.url));
export const OUT = path.join(REPO, 'src', 'server', 'ui-assets.ts');

/** The files the pages may load, in this order; those not on disk are left out: the old page and the home
 *  page, their styles, the ui/ modules, and the shared modules they import (strings.js, which imports only frozen.js). The
 *  daemon holds each tower to shared/tower-contract.js before it answers, so the page loads neither
 *  that nor shared/protocol.js or shared/stage-contract.js. */
export const UI_FILES: readonly string[] = Object.freeze([
  'ui/tower.html', 'ui/tower.css', 'ui/app.js', 'ui/home.html', 'ui/home.css', 'ui/home.js', 'ui/wings.js', 'ui/front.js', 'ui/fold.js', 'ui/drive.js', 'ui/api.js', 'ui/clock.js', 'ui/view.js', 'ui/owned.js', 'ui/tree.js', 'ui/dom.js', 'ui/route.js', 'ui/prefs.js',
  'shared/strings.js', 'shared/frozen.js',
]);

const TYPES: Readonly<Record<string, string>> = Object.freeze({
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
});

/** The whitelisted files that exist now, with their bytes. */
export function present(repo: string = REPO): { name: string; bytes: Buffer }[] {
  return UI_FILES.filter((name) => fs.existsSync(path.join(repo, name))).map((name) => ({ name, bytes: fs.readFileSync(path.join(repo, name)) }));
}

/** The text of src/server/ui-assets.ts for these files. */
export function render(files: readonly { name: string; bytes: Buffer }[]): string {
  const rows = files.map(({ name, bytes }) => {
    const etag = `"${createHash('sha256').update(bytes).digest('hex').slice(0, 32)}"`;
    return `  '${name}': { type: '${TYPES[path.extname(name)]}', etag: '${etag}', hex: '${bytes.toString('hex')}' },`;
  });
  return `// Generated by scripts/embed-ui.ts from ui/ and shared/; do not edit, run the script again.
// The tower page's static files for the peek server (src/server/http.ts), each body as hex: see the
// script's header for why. test/server/ui-assets-drift.test.ts holds this file to the files on disk.
import { frozen } from '../../shared/frozen.js';

export type UiAsset = { type: string; etag: string; hex: string };

export const UI_ASSETS: Readonly<Record<string, UiAsset>> = frozen({
${rows.join('\n')}
});
`;
}

if (import.meta.main) {
  const files = present();
  fs.writeFileSync(OUT, render(files));
  console.log(`embed-ui: ${files.length} files into ${path.relative(REPO, OUT)}: ${files.map((f) => f.name).join(', ')}`);
}
